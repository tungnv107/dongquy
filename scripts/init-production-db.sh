#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=app_password="$APP_DB_PASSWORD" <<'SQL'
CREATE ROLE dongquy_app LOGIN PASSWORD :'app_password';
GRANT CONNECT ON DATABASE dongquy TO dongquy_app;
GRANT USAGE ON SCHEMA public TO dongquy_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO dongquy_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO dongquy_app;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
SQL
